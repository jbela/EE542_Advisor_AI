"""Section schedules and offering history rendered from collected records.

Meeting times, instructors, and seat counts are copied from the Schedule of
Classes record for the requested semester; nothing here is generated by an
LLM. Seat counts are a snapshot from the collection date and say so.
"""
import json
import re
from datetime import datetime

from backend.rag_service import format_term
from rag.advisor_retrieval import asks_schedule
from rag.course_lookup import COURSES_DIR, find_course_offerings


def _clock(value):
    """'13:50' -> '1:50 pm'."""
    match = re.fullmatch(r"(\d{1,2}):(\d{2})", str(value or ""))
    if not match:
        return str(value or "time TBA")
    hour, minute = int(match.group(1)), match.group(2)
    suffix = "am" if hour < 12 else "pm"
    return f"{(hour - 1) % 12 + 1}:{minute} {suffix}"


def _meetings(section):
    slots = []
    for slot in section.get("schedule") or []:
        days = "/".join(slot.get("days") or []) or "Days TBA"
        slots.append(f"{days} {_clock(slot.get('startTime'))}–{_clock(slot.get('endTime'))}")
    return "; ".join(slots) or "meeting time TBA"


def _instructors(section):
    names = [
        f"{i.get('firstName', '').strip()} {i.get('lastName', '').strip()}".strip()
        for i in section.get("instructors") or []
    ]
    return ", ".join(n for n in names if n)


def _as_of(collected_at):
    try:
        return datetime.fromisoformat(str(collected_at)).strftime("%b %d, %Y").replace(" 0", " ")
    except ValueError:
        return None


def section_lines(sections):
    """One line per section; discussion/lab rows inherit no instructor."""
    lines = []
    for section in sections or []:
        kind = section.get("type") or "Section"
        parts = [f"**{kind} {section.get('section_id', '')}**".replace(" **", "**"),
                 _meetings(section)]
        who = _instructors(section)
        if who:
            parts.append(who)
        registered, total = section.get("registered_seats"), section.get("total_seats")
        if isinstance(registered, int) and isinstance(total, int) and total:
            parts.append(f"{registered} of {total} seats registered")
        if section.get("d_clearance"):
            parts.append("requires D-Clearance")
        lines.append("- " + " · ".join(parts))
    return lines


def _main_terms_collected():
    terms = []
    for path in COURSES_DIR.glob("ee_*.json"):
        code = path.stem.split("_", 1)[1]
        if code.isdigit() and code[-1] in "13":  # spring and fall only
            terms.append(code)
    return sorted(terms)


def offering_context(code, term_code):
    """Describe a recent gap before this offering, from collected records only.

    Returns e.g. 'Before Spring 2027, the most recent collected listing was
    Spring 2025; it was not listed in Fall 2025, Spring 2026, or Fall 2026.'
    or None when there is no notable gap (fewer than two missed semesters).
    """
    term_code = str(term_code)
    earlier = [o["term_code"] for o in find_course_offerings(code, max_term=term_code)
               if o["term_code"] != term_code and o["term_code"][-1] in "13"]
    if not earlier:
        return None
    previous = earlier[0]  # newest first
    missed = [t for t in _main_terms_collected() if previous < t < term_code]
    if len(missed) < 2:
        return None
    names = [format_term(t) for t in missed]
    listed = names[0] if len(names) == 1 else ", ".join(names[:-1]) + ", or " + names[-1]
    return (f"Before {format_term(term_code)}, the most recent collected listing of "
            f"{code} was {format_term(previous)}; it was not listed in {listed}.")


def _describe_rule(rule):
    """Plain-language prerequisite rule without inventing AND/OR logic."""
    from backend.prerequisite_service import format_rule

    if rule is None or rule == []:
        return None
    formatted = format_rule(rule)
    if formatted:
        return formatted
    codes = []

    def collect(node):
        if isinstance(node, dict):
            for c in node.get("courses") or []:
                if isinstance(c, str) and c not in codes:
                    codes.append(c)
            for g in node.get("groups") or []:
                collect(g)
    collect(rule)
    return "involving " + ", ".join(codes) if codes else "that could not be parsed"


def prerequisite_change(code, term_code):
    """Explain a change between this listing's prerequisites and the previous
    collected listing's, or None if they match. Older catalogs (and models
    trained on them) may still show the earlier rule."""
    term_code = str(term_code)
    offerings = find_course_offerings(code, max_term=term_code)  # newest first
    current = next((o for o in offerings if o["term_code"] == term_code), None)
    older = [o for o in offerings if o["term_code"] < term_code]
    if current is None or not older:
        return None

    def key(o):
        # Compare USC's raw requirement data, not the display form: verified
        # overrides exist only for some terms and would look like a change.
        raw = o.get("prerequisites")
        if not raw:
            return json.dumps(raw)
        groups = sorted(
            (sorted(opt.get("courseSpace") or "" for opt in g.get("courseOptions") or []),
             g.get("requiredCourses"))
            for g in raw
        )
        return json.dumps(groups)

    if key(older[0]) == key(current):
        return None
    run = [older[0]]
    for o in older[1:]:
        if key(o) != key(run[0]):
            break
        run.append(o)
    newest, oldest = format_term(run[0]["term_code"]), format_term(run[-1]["term_code"])
    span = newest if len(run) == 1 else f"{oldest} through {newest}"
    before = _describe_rule(run[0].get("prerequisites_display"))
    after = _describe_rule(current.get("prerequisites_display"))
    def phrase(rule, verb):
        if not rule:
            return f"{verb} no prerequisites"
        if re.fullmatch(r"[A-Z]{2,5} \d{3}[A-Z]?", rule):
            return f"{verb} {rule} as a prerequisite"
        if rule.startswith(("involving", "that could")):
            return f"{verb} prerequisites {rule}"
        return f"{verb} prerequisites: {rule}"

    before_text = phrase(before, "listed")
    after_text = phrase(after, "lists")
    sentence = (f"This changed recently: collected listings from {span} {before_text}; "
                f"the {format_term(term_code)} listing {after_text}")
    prep = current.get("recommended_preparation")
    if prep:
        sentence += f" and gives recommended preparation: {prep.rstrip('.')}"
    return sentence + "."


def _section_summary(sections):
    types = sorted({(s.get("type") or "Section") for s in sections or []})
    n = len(sections or [])
    return f"{n} section{'s' if n != 1 else ''} ({', '.join(types)})"


def format_change(code, term_code, sections):
    """Note when this listing's section types differ from the previous
    offering's (e.g. discussions dropped). Older descriptions of the course,
    including AI answers trained on them, may still show the old format."""
    term_code = str(term_code)
    earlier = [o for o in find_course_offerings(code, max_term=term_code)
               if o["term_code"] < term_code]
    if not earlier or not sections:
        return None
    previous = earlier[0]
    before = {(s.get("type") or "Section") for s in previous.get("sections") or []}
    now = {(s.get("type") or "Section") for s in sections}
    if not before or before == now:
        return None
    return (f"The section format changed: the {format_term(previous['term_code'])} listing had "
            f"{_section_summary(previous.get('sections'))}; the {format_term(term_code)} listing "
            f"has {_section_summary(sections)}.")


def headline(status, doc):
    """One-line bottom line for 'Can I take X, and when does it meet?'."""
    code, term = doc.get("course_code"), format_term(doc.get("term_code"))
    opener = {
        "satisfied": "**Yes.** You meet the listed prerequisites",
        "not_satisfied": "**Not yet.** You haven't met all the listed prerequisites",
    }.get(status, "**I can't confirm your prerequisites yet** from what you listed")
    lectures = [s for s in doc.get("sections") or [] if (s.get("type") or "").lower() == "lecture"]
    if len(lectures) == 1:
        who = _instructors(lectures[0])
        when = _meetings(lectures[0]) + (f" with {who}" if who else "")
        return f"{opener}, and {code} meets {when} in {term} (one section)."
    if lectures:
        return f"{opener}. {code} has {len(lectures)} lecture sections in {term}, listed below."
    return f"{opener}. {code}'s {term} listing has no lecture section details."


def schedule_block(doc, cite):
    """Markdown block with sections for one exact-term course record."""
    sections = doc.get("sections") or []
    term = format_term(doc.get("term_code"))
    code = doc.get("course_code")
    if not sections:
        return f"The collected {term} listing for {code} has no section details. {cite}"
    lectures = [s for s in sections if (s.get("type") or "").lower() == "lecture"]
    count = len(lectures) or len(sections)
    noun = "lecture section" if lectures else "section"
    header = f"**{code} in {term}** has {count} {noun}{'s' if count != 1 else ''}: {cite}"
    lines = [header, *section_lines(sections)]
    as_of = _as_of(doc.get("collected_at"))
    if any(isinstance(s.get("registered_seats"), int) for s in sections):
        lines.append(f"Seat counts are from the Schedule of Classes as of {as_of}; "
                     "check the live listing before registering." if as_of else
                     "Seat counts are a snapshot; check the live listing before registering.")
    history = [note for note in (
        offering_context(code, doc.get("term_code")),
        format_change(code, doc.get("term_code"), sections),
    ) if note]
    if history:
        lines += ["", "**From 5 years of collected listings:**",
                  *(f"- {note}" for note in history),
                  "- Past listings don't guarantee future offerings."]
    return "\n".join(lines)


def schedule_answer(question, docs, target=None):
    """Deterministic schedule answer for one current-term exact record, or None."""
    if not asks_schedule(question):
        return None
    matches = [
        (i, d) for i, d in enumerate(docs, 1)
        if d.get("retrieval_method") == "exact"
        and (target is None or d.get("course_code") == target)
    ]
    if len(matches) != 1:
        return None
    i, doc = matches[0]
    cite = f"[{i}]" if doc.get("url") else ""
    if doc.get("historical"):
        return (f"{doc.get('course_code')} is not listed in the collected "
                f"{format_term(doc.get('requested_term'))} Schedule of Classes, so I can't give "
                f"its sections for that semester. The most recent collected listing is "
                f"{format_term(doc.get('term_code'))}. {cite}").strip()
    return schedule_block(doc, cite)
